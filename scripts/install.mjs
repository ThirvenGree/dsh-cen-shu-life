import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {LifeEngine} from '../lib/engine.js';
const home=process.env.DSH_HOME||path.join(os.homedir(),'.dsh');
const profile=path.resolve(process.argv[2]||path.join(home,'profiles/desktop'));
const sessionId=process.argv[3];
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const file=path.join(profile,'package.json');
const pkg=JSON.parse(fs.readFileSync(file,'utf8'));
fs.copyFileSync(file,file+'.before-cen-shu-life.bak');
pkg.dependencies||={};pkg.dependencies['dsh-cen-shu-life']='link:'+root.replaceAll('\\','/');
pkg.dsh||={};pkg.dsh.profile||={};pkg.dsh.profile.bundles||=[];
if(!pkg.dsh.profile.bundles.includes('dsh-cen-shu-life'))pkg.dsh.profile.bundles.push('dsh-cen-shu-life');
fs.writeFileSync(file,JSON.stringify(pkg,null,2));
const link=path.join(profile,'node_modules/dsh-cen-shu-life');fs.mkdirSync(path.dirname(link),{recursive:true});
if(!fs.existsSync(link))fs.symlinkSync(root,link,process.platform==='win32'?'junction':'dir');
else if(fs.realpathSync(link)!==fs.realpathSync(root))throw Error('已有安装指向其他目录，请先处理后再安装');
const engine=new LifeEngine({home});if(sessionId)engine.saveConfig({sessionIds:[sessionId]});
console.log('安装完成。重启 DSH，在设置 → 岑舒生活中绑定会话及心情记录。');
