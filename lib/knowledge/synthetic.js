/** Program checks on how a suite was consolidated (the six checks of the old fixed fixture, driven by the suite's spec). */
export function suiteChecks(index, spec = BUILTIN_SPEC) {
  const items = Object.values(index.items), shared = items.filter(i => i.visibility === 'shared');
  const itemOf = k => items.find(i => i.sources.includes(k));
  const has = (i, w) => norm(i.content).includes(norm(w));
  const [dupA, dupB] = spec.dedup, [progA, progB] = spec.progress, c = spec.correction;
  return {
    dedup: index.sources[dupB]?.relation === 'duplicate' || index.sources[dupA]?.relation === 'duplicate' || Boolean(itemOf(dupB) && itemOf(dupB) === itemOf(dupA)),
    progressLinked: index.sources[progB]?.relation === 'progress' || shared.some(i => i.links.some(l => l.relation === 'progress')) || Boolean(itemOf(progB) && itemOf(progB) === itemOf(progA)),
    planState: items.some(i => i.sources.includes(spec.plan) && i.stage === 'intended'),
    correction: shared.some(i => i.status === 'active' && has(i, c.newWord)) && !shared.some(i => i.status === 'active' && has(i, c.oldWord) && !has(i, c.newWord)),
    irrelevantIgnored: index.sources[spec.irrelevant]?.relation === 'irrelevant',
    isolation: !shared.some(i => spec.privateWords.some(w => has(i, w))),
  };
}

